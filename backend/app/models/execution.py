"""
Execution domain models and schemas for AgentOps — Abyssal Intelligence.

Defines:
- ExecutionStatus enum (pending, running, completed, failed, cancelled)
- ExecutionStep (atomic execution status and output for a workflow step)
- ExecutionBase (shared execution attributes)
- ExecutionCreate (request payload to trigger a workflow execution)
- ExecutionUpdate (internal/engine payload to update execution state)
- ExecutionInDB (internal MongoDB document representation)
- ExecutionResponse (API response model with stringified IDs)
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator
from app.models.common import TimestampedModel


class ExecutionStatus(str, Enum):
    """
    Lifecycle status of a workflow execution.
    """
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class ExecutionStep(BaseModel):
    """
    Represents the runtime execution state and output of an individual workflow step.
    """
    step_id: str = Field(
        ...,
        alias="stepId",
        min_length=1,
        max_length=100,
        description="Unique identifier for the step matching the workflow definition",
        examples=["step-01", "sonar-ping"],
    )
    name: str = Field(
        ...,
        min_length=1,
        max_length=100,
        description="Human-readable name of the executed step",
        examples=["Sonar Calibration"],
    )
    agent_id: Optional[str] = Field(
        default=None,
        alias="agentId",
        description="Optional identifier of the agent executing this step",
        examples=["agt-001", "654a1b2c3d4e5f6a7b8c9d0e"],
    )
    order: int = Field(
        ...,
        ge=0,
        description="Execution sequence order (non-negative integer: 0, 1, 2...)",
        examples=[0],
    )
    status: ExecutionStatus = Field(
        default=ExecutionStatus.PENDING,
        description="Current execution status of this step",
    )
    started_at: Optional[datetime] = Field(
        default=None,
        alias="startedAt",
        description="UTC timestamp when this step started executing",
    )
    completed_at: Optional[datetime] = Field(
        default=None,
        alias="completedAt",
        description="UTC timestamp when this step finished executing",
    )
    input_data: Optional[Dict[str, Any]] = Field(
        default=None,
        alias="inputData",
        description="Input parameters or payload supplied to this step",
    )
    output_data: Optional[Dict[str, Any]] = Field(
        default=None,
        alias="outputData",
        description="Output payload or results generated by this step",
    )
    error: Optional[str] = Field(
        default=None,
        description="Error details or traceback if step execution failed",
    )

    model_config = ConfigDict(
        populate_by_name=True,
        str_strip_whitespace=True,
    )

    @field_validator("step_id", "name", mode="before")
    @classmethod
    def validate_non_empty_strings(cls, v: str) -> str:
        if isinstance(v, str) and not v.strip():
            raise ValueError("Field cannot be empty or purely whitespace")
        return v

    @model_validator(mode="after")
    def validate_step_timestamps(self) -> "ExecutionStep":
        if self.started_at:
            if self.started_at.tzinfo is None:
                self.started_at = self.started_at.replace(tzinfo=timezone.utc)
            else:
                self.started_at = self.started_at.astimezone(timezone.utc)
        if self.completed_at:
            if self.completed_at.tzinfo is None:
                self.completed_at = self.completed_at.replace(tzinfo=timezone.utc)
            else:
                self.completed_at = self.completed_at.astimezone(timezone.utc)
        if self.started_at and self.completed_at:
            if self.completed_at < self.started_at:
                raise ValueError("completed_at cannot be earlier than started_at")
        return self


class ExecutionBase(BaseModel):
    """
    Base attributes shared across Execution schemas.
    """
    workflow_id: str = Field(
        ...,
        alias="workflowId",
        min_length=1,
        description="Identifier of the workflow being executed",
        examples=["wf-001", "654a1b2c3d4e5f6a7b8c9d0e"],
    )
    status: ExecutionStatus = Field(
        default=ExecutionStatus.PENDING,
        description="Overall lifecycle status of the workflow execution",
    )
    started_at: Optional[datetime] = Field(
        default=None,
        alias="startedAt",
        description="UTC timestamp when execution started",
    )
    completed_at: Optional[datetime] = Field(
        default=None,
        alias="completedAt",
        description="UTC timestamp when execution reached a terminal state",
    )
    steps: List[ExecutionStep] = Field(
        default_factory=list,
        description="Ordered list of step execution states",
    )
    parameters: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Runtime parameters or environment variables for the execution",
    )
    error: Optional[str] = Field(
        default=None,
        description="Top-level error message or diagnostics if execution failed",
    )

    model_config = ConfigDict(
        populate_by_name=True,
        str_strip_whitespace=True,
    )

    @field_validator("workflow_id", mode="before")
    @classmethod
    def validate_non_empty_workflow_id(cls, v: str) -> str:
        if isinstance(v, str) and not v.strip():
            raise ValueError("workflow_id cannot be empty or purely whitespace")
        return v

    @model_validator(mode="after")
    def validate_execution_timestamps(self) -> "ExecutionBase":
        if self.started_at and self.started_at.tzinfo is None:
            self.started_at = self.started_at.replace(tzinfo=timezone.utc)
        if self.completed_at and self.completed_at.tzinfo is None:
            self.completed_at = self.completed_at.replace(tzinfo=timezone.utc)
        if self.started_at and self.completed_at:
            if self.completed_at < self.started_at:
                raise ValueError("completed_at cannot be earlier than started_at")
        return self


class ExecutionCreate(BaseModel):
    """
    Request schema to trigger a new workflow execution.
    """
    workflow_id: str = Field(
        ...,
        alias="workflowId",
        min_length=1,
        description="Workflow identifier to execute",
        examples=["654a1b2c3d4e5f6a7b8c9d0e"],
    )
    parameters: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional input parameters passed to initialize the workflow run",
    )

    model_config = ConfigDict(
        populate_by_name=True,
        str_strip_whitespace=True,
    )

    @field_validator("workflow_id", mode="before")
    @classmethod
    def validate_non_empty_workflow_id(cls, v: str) -> str:
        if isinstance(v, str) and not v.strip():
            raise ValueError("workflow_id cannot be empty or purely whitespace")
        return v


class ExecutionUpdate(BaseModel):
    """
    Schema for updating execution progress, step transitions, and completion states.
    All fields are optional.
    """
    status: Optional[ExecutionStatus] = None
    started_at: Optional[datetime] = Field(default=None, alias="startedAt")
    completed_at: Optional[datetime] = Field(default=None, alias="completedAt")
    steps: Optional[List[ExecutionStep]] = None
    parameters: Optional[Dict[str, Any]] = None
    error: Optional[str] = None

    model_config = ConfigDict(
        populate_by_name=True,
        str_strip_whitespace=True,
    )


class ExecutionInDB(TimestampedModel, ExecutionBase):
    """
    Internal representation of an Execution document stored in MongoDB.
    Includes database unique identifier and created/updated timestamps.
    """
    id: Optional[str] = Field(default=None, description="Database unique identifier (stringified ObjectId)")


class ExecutionResponse(TimestampedModel, ExecutionBase):
    """
    API Response model returned to clients.
    Safely serializes MongoDB ObjectId to string ID and hides raw _id.
    """
    id: str = Field(description="Unique string identifier (e.g. stringified ObjectId)")

    model_config = ConfigDict(
        populate_by_name=True,
        from_attributes=True,
    )
